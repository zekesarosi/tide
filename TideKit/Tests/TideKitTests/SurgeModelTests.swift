import XCTest
@testable import TideKit

final class SurgeModelTests: XCTestCase {
    /// Deterministic pseudo-random generator for reproducible synthetic storms.
    struct LCG {
        var state: UInt64
        mutating func next() -> Double {
            state = state &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
            return Double(state >> 11) / Double(1 << 53)
        }
        mutating func normal() -> Double {
            let u1 = max(next(), 1e-12), u2 = next()
            return (-2 * log(u1)).squareRoot() * cos(2 * .pi * u2)
        }
    }

    let start = Date(timeIntervalSince1970: 1_790_000_000)

    /// Synthetic weather: passing lows every ~4 days with rotating winds.
    func syntheticForcing(hours: Int) -> [MetSample] {
        var rng = LCG(state: 42)
        return (0..<hours).map { h in
            let t = Double(h)
            let pressure = 1012 - 18 * pow(sin(t / 96 * .pi), 8) + 2 * rng.normal()
            let speed = max(0, 6 + 6 * sin(t / 60) + 1.5 * rng.normal())
            let dir = Angle.normalize(60 + 120 * sin(t / 80))
            return MetSample(date: start + t * 3_600, pressure: pressure, windSpeed: speed, windDirection: dir)
        }
    }

    /// Residual generated by a known model + AR(1) noise.
    func syntheticResiduals(forcing: [MetSample], ib: Double = -0.01, windCoef: Double = 0.0015, offset: Double = 0.12) -> TimeSeries {
        let (dates, rows) = SurgeModel.featureRows(forcing: forcing, features: SurgeModel.defaultFeatures)
        var rng = LCG(state: 7)
        var e = 0.0
        return TimeSeries(points: zip(dates, rows).map { d, r in
            e = 0.9 * e + 0.01 * rng.normal()
            // r = [1, P3, X3, Y3, X18, Y18]; set-up from easterly-ish slow wind (−u).
            let v = offset + ib * r[1] - windCoef * r[4] + 0.5 * windCoef * r[5] + e
            return TimeSeriesPoint(date: d, value: v)
        })
    }

    func testRecoversKnownResponse() throws {
        let forcing = syntheticForcing(hours: 24 * 33)
        let residuals = syntheticResiduals(forcing: forcing)
        let model = try SurgeModel.fit(residuals: residuals, forcing: forcing)
        let d = model.diagnostics
        XCTAssertTrue(d.calibrated)
        XCTAssertGreaterThan(try XCTUnwrap(d.rSquared), 0.85)
        XCTAssertEqual(try XCTUnwrap(d.inverseBarometerCmPerHPa), -1.0, accuracy: 0.15)
        XCTAssertEqual(model.coefficients[0], 0.12, accuracy: 0.03)
        // Learned persistence should keep a slowly decaying anomaly (true AR φ = 0.9).
        XCTAssertGreaterThan(model.phi, 0.7)
        // Synthetic set-up ∝ −u + 0.5·v: water rises for wind blowing toward
        // (−1, 0.5), i.e. *from* 116.6° true.
        let dir = try XCTUnwrap(d.dominantWindDirection)
        XCTAssertEqual(dir, 116.6, accuracy: 10)
        XCTAssertLessThan(try XCTUnwrap(d.hindcast24hRMS), try XCTUnwrap(d.persistence24hRMS))
    }

    func testForecastUncertaintyGrowsAndPersistenceDecays() throws {
        let forcing = syntheticForcing(hours: 24 * 36 + 1)
        let residuals = syntheticResiduals(forcing: forcing)
        let issue = start + Double(24 * 33) * 3_600
        let history = residuals.sliced(from: start, to: issue).mapValues { $0 + 0 }
        // Inject a +20 cm unexplained anomaly at issue time.
        let bumped = TimeSeries(points: history.points.map { p in
            p.date > issue - 4 * 3_600 ? TimeSeriesPoint(date: p.date, value: p.value + 0.2) : p
        })
        let model = try SurgeModel.fit(residuals: history, forcing: forcing.filter { $0.date <= issue })
        let fc = model.forecast(forcing: forcing, recentResiduals: bumped, issueTime: issue, horizonHours: 72)
        XCTAssertEqual(fc.count, 72)
        XCTAssertGreaterThan(fc[0].persistenceComponent, 0.12)
        XCTAssertLessThan(abs(fc[71].persistenceComponent), 0.01)
        XCTAssertLessThan(fc[0].sigma, fc[71].sigma)
        for p in fc {
            XCTAssertEqual(p.mean, p.offsetComponent + p.pressureComponent + p.windComponent + p.persistenceComponent, accuracy: 1e-9)
        }
    }

    func testDistantWeatherIsDampedAndWidensTheBand() throws {
        let forcing = syntheticForcing(hours: 24 * 45 + 1)
        let residuals = syntheticResiduals(forcing: forcing)
        let issue = start + Double(24 * 33) * 3_600
        let model = try SurgeModel.fit(residuals: residuals.sliced(from: start, to: issue),
                                       forcing: forcing.filter { $0.date <= issue })
        // Same forecast, with a deep low arriving either 1 or 9 days out.
        func storm(at hours: Double) -> [MetSample] {
            forcing.map { s in
                var s = s
                let x = (s.date.timeIntervalSince(issue) / 3_600 - hours) / 12
                s.pressure -= 30 * exp(-x * x)
                return s
            }
        }
        func response(_ hours: Double) throws -> (shift: Double, sigma: Double) {
            let calm = model.forecast(forcing: forcing, recentResiduals: residuals, issueTime: issue, horizonHours: 24 * 11)
            let stormy = model.forecast(forcing: storm(at: hours), recentResiduals: residuals, issueTime: issue, horizonHours: 24 * 11)
            let i = try XCTUnwrap(calm.firstIndex { abs($0.date.timeIntervalSince(issue) / 3_600 - hours) < 0.5 })
            return (stormy[i].mean - calm[i].mean, stormy[i].sigma - calm[i].sigma)
        }
        let near = try response(24), far = try response(24 * 9)
        XCTAssertGreaterThan(near.shift, 0.1)                       // inverse barometer, taken at face value
        XCTAssertLessThan(far.shift, near.shift * 0.4)               // 9 days out: mostly distrusted…
        XCTAssertGreaterThan(far.sigma, near.sigma + near.shift * 0.4) // …and carried as uncertainty
        XCTAssertEqual(SurgeModel.weatherSkill(atLead: 24), 1)
        XCTAssertLessThan(SurgeModel.weatherSkill(atLead: 24 * 9), 0.3)
    }

    func testInsufficientData() {
        let forcing = syntheticForcing(hours: 60)
        XCTAssertThrowsError(try SurgeModel.fit(residuals: syntheticResiduals(forcing: forcing), forcing: forcing))
    }

    func testRidgeMatchesOrdinaryLeastSquaresForSmallLambda() throws {
        var X: [[Double]] = [], y: [Double] = []
        for i in 0..<200 {
            let a = Double(i % 17), b = Double((i * 7) % 13)
            X.append([1, a, b]); y.append(2 + 0.5 * a - 0.25 * b)
        }
        let beta = try XCTUnwrap(LinearAlgebra.ridge(X, y, lambda: 1e-9))
        XCTAssertEqual(beta[0], 2, accuracy: 1e-6)
        XCTAssertEqual(beta[1], 0.5, accuracy: 1e-6)
        XCTAssertEqual(beta[2], -0.25, accuracy: 1e-6)
    }

    func testNormalCDF() {
        XCTAssertEqual(Stats.normalCDF(0), 0.5, accuracy: 1e-12)
        XCTAssertEqual(Stats.normalCDF(1.959964), 0.975, accuracy: 1e-5)
        XCTAssertEqual(Stats.zForCentralInterval(0.8), 1.2816, accuracy: 1e-3)
    }
}

final class ForecasterTests: XCTestCase {
    let now = Date(timeIntervalSince1970: 1_793_570_400) // 2026-11-02T00:00Z

    func batteryPredictor() throws -> HarmonicPredictor {
        let c = try NOAACoopsDecoding.harmonicConstituents(from: Fixtures.data("harcon_8518750"))
        return HarmonicPredictor(constituents: c, meanLevel: 0.783) // MSL above MLLW
    }

    func forcing(from: Date, hours: Int, stormAt: Date? = nil) -> [MetSample] {
        (0..<hours).map { h in
            let t = from + Double(h) * 3_600
            var p = 1015.0, w = 4.0
            if let s = stormAt {
                let x = t.timeIntervalSince(s) / 3_600 / 18
                p -= 25 * exp(-x * x)
                w += 14 * exp(-x * x)
            }
            return MetSample(date: t, pressure: p, windSpeed: w, windDirection: 70)
        }
    }

    func testEndToEndStormRaisesTotalAndFloodProbability() throws {
        let predictor = try batteryPredictor()
        let trainStart = now - 33 * 86_400
        let horizonHours = 96
        let storm = now + 48 * 3_600
        // Two historical storms so the model can learn the response.
        let historicalStorms = [now - 20 * 86_400, now - 9 * 86_400]
        var met = forcing(from: trainStart, hours: (33 * 24) + horizonHours + 2)
        met = met.map { s in
            var s = s
            for c in historicalStorms + [storm] {
                let x = s.date.timeIntervalSince(c) / 3_600 / 18
                s.pressure -= 25 * exp(-x * x)
                s.windSpeed += 14 * exp(-x * x)
            }
            return s
        }
        let (dates, rows) = SurgeModel.featureRows(forcing: met, features: SurgeModel.defaultFeatures)
        // True surge: IB + slow wind set-up (+x component negative for ENE winds).
        var truth: [Date: Double] = [:]
        for (d, r) in zip(dates, rows) { truth[d] = 0.1 - 0.01 * r[1] - 0.002 * r[4] - 0.001 * r[5] }
        var obs: [TimeSeriesPoint] = []
        var t = trainStart
        while t <= now {
            let hour = Date(timeIntervalSince1970: (t.timeIntervalSince1970 / 3_600).rounded() * 3_600)
            obs.append(.init(date: t, value: predictor.height(at: t) + (truth[hour] ?? 0.1)))
            t += 360
        }
        let thresholds = FloodThresholds(datum: .mllw, action: 1.9, minor: 2.2, moderate: 2.6, major: 3.0)

        // Official guidance in a datum 0.5 m lower than ours (NAVD-like shift).
        let shift = -0.5
        var offObs: [TimeSeriesPoint] = [], offFc: [TimeSeriesPoint] = []
        var u = now - 3 * 86_400
        while u <= now + 60 * 3_600 {
            let hour = Date(timeIntervalSince1970: (u.timeIntervalSince1970 / 3_600).rounded() * 3_600)
            let v = predictor.height(at: u) + (truth[hour] ?? 0.1) + shift
            if u <= now { offObs.append(.init(date: u, value: v)) } else { offFc.append(.init(date: u, value: v)) }
            u += 3_600
        }
        let official = OfficialForecast(source: .nwps, issued: now - 6 * 3_600, observed: TimeSeries(points: offObs),
                                        forecast: TimeSeries(points: offFc), datumHint: nil)

        let station = Station(source: .noaaCoops, code: "8518750", name: "The Battery", latitude: 40.7, longitude: -74.01)
        let input = ForecastInputs(station: station, datum: .mllw, issueTime: now, horizonHours: horizonHours,
                                   astronomical: .harmonic(predictor), observations: TimeSeries(points: obs),
                                   forcing: met, official: official, thresholds: thresholds)
        let f = TotalWaterLevelForecaster.forecast(input)

        XCTAssertEqual(f.method, .calibrated)
        XCTAssertTrue(f.notes.contains { $0.contains("-0.50") || $0.contains("+0.50") }, "\(f.notes)")
        XCTAssertGreaterThan(f.surge.filter { $0.officialWeight > 0 }.count, 24)

        // Peak surge near the storm, close to the truth.
        let peak = try XCTUnwrap(f.surge.max { $0.surge < $1.surge })
        XCTAssertLessThan(abs(peak.date.timeIntervalSince(storm)), 12 * 3_600)
        let trueHour = Date(timeIntervalSince1970: (peak.date.timeIntervalSince1970 / 3_600).rounded() * 3_600)
        XCTAssertEqual(peak.surge, try XCTUnwrap(truth[trueHour]), accuracy: 0.08)

        // Events: alternate high/low, probabilities monotone across categories.
        XCTAssertGreaterThan(f.events.count, 6)
        for e in f.events where e.kind == .high {
            let pMinor = try XCTUnwrap(e.exceedance[.minor]), pMod = try XCTUnwrap(e.exceedance[.moderate])
            XCTAssertGreaterThanOrEqual(pMinor, pMod)
            XCTAssertEqual(e.total, e.astronomical + e.surge, accuracy: 1e-9)
        }
        let stormHigh = try XCTUnwrap(f.events.filter { $0.kind == .high }.min { abs($0.date.timeIntervalSince(storm)) < abs($1.date.timeIntervalSince(storm)) })
        let calmHigh = try XCTUnwrap(f.events.first { $0.kind == .high })
        XCTAssertGreaterThan(stormHigh.surge, calmHigh.surge + 0.15)

        // Bands bracket the mean.
        for (m, (lo, hi)) in zip(f.total.points, zip(f.totalLower.points, f.totalUpper.points)) {
            XCTAssertLessThanOrEqual(lo.value, m.value)
            XCTAssertGreaterThanOrEqual(hi.value, m.value)
        }
    }

    func testLongRangeOutlookRunsPastTheWeatherForecast() throws {
        let predictor = try batteryPredictor()
        let trainStart = now - 33 * 86_400
        let weatherDays = 10.0
        let met = forcing(from: trainStart, hours: 33 * 24 + Int(weatherDays * 24))
        // Observed: tide plus a steady +0.12 m anomaly with a little wobble.
        var obs: [TimeSeriesPoint] = []
        var t = trainStart
        while t <= now {
            obs.append(.init(date: t, value: predictor.height(at: t) + 0.12 + 0.03 * sin(t.timeIntervalSince1970 / 40_000)))
            t += 360
        }
        let station = Station(source: .noaaCoops, code: "8518750", name: "The Battery", latitude: 40.7, longitude: -74.01)
        let horizonHours = 90 * 24
        let input = ForecastInputs(station: station, datum: .mllw, issueTime: now, horizonHours: horizonHours,
                                   astronomical: .harmonic(predictor), observations: TimeSeries(points: obs), forcing: met)
        let f = TotalWaterLevelForecaster.forecast(input)

        let weatherEnd = try XCTUnwrap(f.weatherHorizon)
        XCTAssertLessThanOrEqual(weatherEnd, now + weatherDays * 86_400)
        XCTAssertTrue(f.notes.contains { $0.contains("weather forecast ends") }, "\(f.notes)")

        // The total curve and the tide events reach the horizon.
        let end = now + Double(horizonHours) * 3_600
        XCTAssertGreaterThan(try XCTUnwrap(f.total.last?.date), end - 3_600)
        XCTAssertGreaterThan(try XCTUnwrap(f.events.last?.date), end - 13 * 3_600)
        XCTAssertGreaterThan(f.events.count, 300)

        // Far out, the surge sits at the station's typical anomaly and the
        // band at its typical spread (0.03 m wobble → floor of 0.05 m);
        // events stay consistent.
        let far = f.surge.filter { $0.date > weatherEnd + 20 * 86_400 }
        XCTAssertFalse(far.isEmpty)
        for p in far {
            XCTAssertEqual(p.surge, 0.12, accuracy: 0.03)
            XCTAssertEqual(p.sigma, 0.05, accuracy: 0.01)
        }
        for e in f.events { XCTAssertEqual(e.total, e.astronomical + e.surge, accuracy: 1e-9) }
    }

    func testDailyBriefingExplainsTheSurgeAtTheDaysPeak() throws {
        let predictor = try batteryPredictor()
        let trainStart = now - 33 * 86_400
        let met = forcing(from: trainStart, hours: 33 * 24 + 10 * 24)
        // Water running a steady +0.3 m above the tide table.
        var obs: [TimeSeriesPoint] = []
        var t = trainStart
        while t <= now {
            obs.append(.init(date: t, value: predictor.height(at: t) + 0.3 + 0.02 * sin(t.timeIntervalSince1970 / 40_000)))
            t += 360
        }
        let station = Station(source: .noaaCoops, code: "8518750", name: "The Battery", latitude: 40.7, longitude: -74.01)
        let f = TotalWaterLevelForecaster.forecast(ForecastInputs(
            station: station, datum: .mllw, issueTime: now, horizonHours: 30 * 24,
            astronomical: .harmonic(predictor), observations: TimeSeries(points: obs), forcing: met))
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = TimeZone(identifier: "America/New_York")!

        let tomorrow = try XCTUnwrap(cal.dateInterval(of: .day, for: now + 86_400))
        let b = try XCTUnwrap(DailyBriefing.make(forecast: f, day: tomorrow))
        XCTAssertFalse(b.isOutlook)
        XCTAssertGreaterThanOrEqual(b.highs.count, 1)
        XCTAssertGreaterThanOrEqual(b.highs.count + b.lows.count, 3)
        let peak = try XCTUnwrap(b.peak)
        XCTAssertEqual(peak.total, b.highs.map(\.total).max())
        XCTAssertEqual(try XCTUnwrap(b.surge), 0.3, accuracy: 0.1)
        // Explained, largest first, and adding up to (about) the surge.
        XCTAssertFalse(b.drivers.isEmpty)
        XCTAssertEqual(b.drivers, b.drivers.sorted { abs($0.value) > abs($1.value) })
        XCTAssertEqual(b.drivers.reduce(0) { $0 + $1.value }, peak.surge, accuracy: 0.05)

        // Past the weather forecast: tides, but no breakdown.
        let late = try XCTUnwrap(cal.dateInterval(of: .day, for: now + 25 * 86_400))
        let o = try XCTUnwrap(DailyBriefing.make(forecast: f, day: late))
        XCTAssertTrue(o.isOutlook)
        XCTAssertTrue(o.drivers.isEmpty)
        XCTAssertFalse(o.highs.isEmpty)
    }

    func testNoObservationsFallsBackToUncalibrated() throws {
        let predictor = try batteryPredictor()
        let station = Station(source: .ukAdmiralty, code: "0001", name: "Test", latitude: 50, longitude: -1)
        let input = ForecastInputs(station: station, datum: .chartDatum, issueTime: now, horizonHours: 48,
                                   astronomical: .harmonic(predictor), observations: .empty,
                                   forcing: forcing(from: now - 3 * 86_400, hours: 24 * 6))
        let f = TotalWaterLevelForecaster.forecast(input)
        XCTAssertEqual(f.method, .uncalibrated)
        XCTAssertFalse(f.model.calibrated)
        XCTAssertFalse(f.events.isEmpty)
        XCTAssertGreaterThan(f.surge.first?.sigma ?? 0, 0.1)
    }

    func testNearbyStormInflatesUncertainty() throws {
        let predictor = try batteryPredictor()
        let station = Station(source: .noaaCoops, code: "x", name: "x", latitude: 40.7, longitude: -74.0)
        let storm = TropicalCyclone(id: "al01", name: "Test", classification: "HU", latitude: 37, longitude: -72)
        let base = ForecastInputs(station: station, datum: .mllw, issueTime: now, horizonHours: 24,
                                  astronomical: .harmonic(predictor), observations: .empty,
                                  forcing: forcing(from: now - 3 * 86_400, hours: 24 * 5))
        var stormy = base
        stormy.storms = [storm]
        let a = TotalWaterLevelForecaster.forecast(base), b = TotalWaterLevelForecaster.forecast(stormy)
        XCTAssertEqual(b.nearbyStorms.count, 1)
        XCTAssertGreaterThan(b.surge[0].sigma, a.surge[0].sigma * 1.5)
        XCTAssertTrue(b.notes.contains { $0.contains("NHC") })
    }

    func testNonTidalUsesMeanLevelBaseline() {
        // Great Lakes style: level ~174 m with a wind-driven seiche, no tide.
        let start = now - 32 * 86_400
        let met = forcing(from: start, hours: 32 * 24 + 50)
        var obs: [TimeSeriesPoint] = []
        var t = start
        while t <= now {
            let h = t.timeIntervalSince(start) / 3_600
            obs.append(.init(date: t, value: 174.2 + 0.1 * sin(h / 30)))
            t += 360
        }
        let station = Station(source: .noaaCoops, code: "9063020", name: "Buffalo", latitude: 42.9, longitude: -78.9, isTidal: false)
        let f = TotalWaterLevelForecaster.forecast(ForecastInputs(
            station: station, datum: .igld, issueTime: now, horizonHours: 48, astronomical: .none,
            observations: TimeSeries(points: obs), forcing: met))
        XCTAssertTrue(f.notes.contains { $0.contains("Non-tidal") })
        XCTAssertTrue(f.events.isEmpty)
        XCTAssertLessThan(abs(f.surge.first?.surge ?? 99), 0.3)       // anomaly, not 174 m
        XCTAssertEqual(f.total.first?.value ?? 0, 174.2, accuracy: 0.3) // total is still absolute level
        XCTAssertFalse(f.model.usesTideInteraction)
    }
}
